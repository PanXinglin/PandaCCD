"""Host driver for batch_rotation_test.dart; use only a disposable emulator.
Approves/denies OS deletion of media generated by that test and rotates its UI.
Usage: python3 tool/drive_batch_rotation_test.py <adb> <flutter-test-log>
"""
import re
import subprocess
import sys
import time
from pathlib import Path
from xml.etree import ElementTree as E
adb, logfile = sys.argv[1:]
log = Path(logfile)
def adb_run(*args):
    return subprocess.check_output([adb, *args], text=True)
def wait(marker, timeout=300):
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        s = log.read_text() if log.exists() else ''
        if marker in s: return
        if 'Some tests failed' in s or 'BUILD FAILED' in s: raise SystemExit(s[-2500:])
        time.sleep(.25)
    raise SystemExit('Missing test marker: ' + marker)
def answer_delete(allow):
    end = time.monotonic() + 30
    while time.monotonic() < end:
        state = adb_run('shell', 'dumpsys', 'activity', 'activities')
        if re.search(r'topResumedActivity=.*media.*PermissionActivity', state):
            adb_run('shell', 'uiautomator', 'dump', '/sdcard/panda-batch-test.xml')
            root = E.fromstring(adb_run('shell', 'cat', '/sdcard/panda-batch-test.xml'))
            titles = [n.get('text', '') for n in root.iter('node') if n.get('resource-id', '').endswith('/dialog_title')]
            if not any('delete' in t.lower() for t in titles): raise SystemExit('Unexpected system prompt')
            for n in root.iter('node'):
                if n.get('resource-id') == ('android:id/button1' if allow else 'android:id/button2'):
                    a,b,c,d=map(int,re.findall(r'\d+',n.get('bounds')))
                    adb_run('shell','input','tap',str((a+c)//2),str((b+d)//2))
                    print('Allowed' if allow else 'Denied', 'batch deletion', flush=True)
                    return
        time.sleep(.25)
    raise SystemExit('No OS batch delete prompt')
adb_run('shell','settings','put','system','accelerometer_rotation','0')
adb_run('shell','settings','put','system','user_rotation','0')
wait('BATCH_PERMISSIONS_READY')
adb_run('shell','pm','grant','com.pandaccd.panda_ccd','android.permission.READ_MEDIA_IMAGES')
adb_run('shell','pm','grant','com.pandaccd.panda_ccd','android.permission.CAMERA')
wait('BATCH_DENY_READY'); answer_delete(False)
wait('BATCH_ALLOW_READY'); answer_delete(True)
wait('ROTATE_LANDSCAPE_READY')
adb_run('shell','settings','put','system','accelerometer_rotation','0')
adb_run('shell','settings','put','system','user_rotation','1')
print('Rotated landscape', flush=True)
wait('ROTATE_PORTRAIT_READY')
adb_run('shell','settings','put','system','user_rotation','0')
print('Rotated portrait', flush=True)
wait('All tests passed!',60)
